#!/usr/bin/env node
/**
 * KONFRM AI Design Skill Synchronizer
 *
 * Generates lightweight discovery shims in .agents/skills/ and .zcode/skills/
 * pointing directly to the canonical source of truth in docs/ai/skills/.
 * Prevents PR bloat and duplicate storage while ensuring full discovery across
 * Codex, Antigravity, and ZCode.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');

const SOURCE_DIR = path.join(projectRoot, 'docs', 'ai', 'skills');
const TARGET_DIRS = [
  path.join(projectRoot, '.agents', 'skills'), // Codex & Antigravity
  path.join(projectRoot, '.zcode', 'skills'),  // ZCode
];

console.log('====================================================');
console.log('KONFRM AI Design Skill Synchronizer (Thin Shim Mode)');
console.log('====================================================');
console.log(`Canonical Source: docs/ai/skills`);

if (!fs.existsSync(SOURCE_DIR)) {
  console.error(`[ERROR]: Canonical source directory does not exist: ${SOURCE_DIR}`);
  process.exit(1);
}

const skills = fs.readdirSync(SOURCE_DIR, { withFileTypes: true })
  .filter(dirent => dirent.isDirectory())
  .map(dirent => dirent.name);

console.log(`Found ${skills.length} governed skills in canonical source:`);
skills.forEach(s => console.log(`  - ${s}`));
console.log();

const MANAGED_MARKER = '<!-- GENERATED BY KONFRM SKILL SYNCHRONIZER - DO NOT EDIT DIRECTLY -->';

// Synchronize thin shims to each target directory
for (const targetDir of TARGET_DIRS) {
  const relTarget = path.relative(projectRoot, targetDir).replaceAll('\\', '/');
  console.log(`Generating thin discovery shims in -> ${relTarget}...`);

  if (!fs.existsSync(targetDir)) {
    fs.mkdirSync(targetDir, { recursive: true });
  }

  // 1. Process each canonical skill
  for (const skill of skills) {
    const srcSkillMd = path.join(SOURCE_DIR, skill, 'SKILL.md');
    const destSkillDir = path.join(targetDir, skill);
    const destSkillMd = path.join(destSkillDir, 'SKILL.md');

    if (!fs.existsSync(srcSkillMd)) {
      console.warn(`  [WARN]: Missing SKILL.md in source: ${skill}`);
      continue;
    }

    if (fs.existsSync(destSkillDir)) {
      // Check for unexpected files in destination directory
      const existingEntries = fs.readdirSync(destSkillDir);
      const unexpectedFiles = existingEntries.filter(entry => entry !== 'SKILL.md');
      if (unexpectedFiles.length > 0) {
        console.error(`[SAFETY ERROR]: Destination directory ${destSkillDir} contains unexpected files: ${unexpectedFiles.join(', ')}.`);
        console.error(`Synchronization stopped to prevent accidental deletion or corruption of unmanaged files.`);
        process.exit(1);
      }

      // If SKILL.md exists, verify it is a managed shim before overwriting
      if (fs.existsSync(destSkillMd)) {
        const existingContent = fs.readFileSync(destSkillMd, 'utf8');
        const isManaged = existingContent.includes(MANAGED_MARKER) || existingContent.includes('This is an agent discovery shim.');
        if (!isManaged) {
          console.error(`[SAFETY ERROR]: Destination file ${destSkillMd} is not a synchronizer-managed discovery shim.`);
          console.error(`Synchronization stopped to prevent overwriting custom content.`);
          process.exit(1);
        }
      }
    } else {
      fs.mkdirSync(destSkillDir, { recursive: true });
    }

    // Extract frontmatter from canonical SKILL.md
    const srcContent = fs.readFileSync(srcSkillMd, 'utf8');
    const fmMatch = srcContent.match(/^---\r?\n([\s\S]*?)\r?\n---/);
    let frontmatter = `name: ${skill}\ndescription: "KONFRM governed design skill: ${skill}."`;
    if (fmMatch) {
      frontmatter = fmMatch[1].trim();
    }

    // Author thin discovery shim with managed marker
    const shimContent = [
      '---',
      frontmatter,
      '---',
      MANAGED_MARKER,
      '',
      `# ${skill} (Discovery Shim)`,
      '',
      'This is an agent discovery shim. The canonical, governed implementation and reference material for this skill is maintained in the KONFRM repository at:',
      '',
      `\`docs/ai/skills/${skill}/SKILL.md\``,
      '',
      `> Refer directly to \`docs/ai/skills/${skill}/SKILL.md\` for complete instructions, guardrails, and usage contracts.`,
      '',
    ].join('\n');

    fs.writeFileSync(destSkillMd, shimContent, 'utf8');
  }

  // Read native runtime brains from .agents/SKILL_MANIFEST.yaml to prevent pruning
  let nativeRuntimeBrains = [];
  const manifestPath = path.join(projectRoot, '.agents', 'SKILL_MANIFEST.yaml');
  if (fs.existsSync(manifestPath)) {
    const manifestText = fs.readFileSync(manifestPath, 'utf8');
    const brainsSectionMatch = manifestText.match(/brains:([\s\S]*?)(?=\n[a-zA-Z0-9_-]+:|$)/);
    const brainsSection = brainsSectionMatch ? brainsSectionMatch[1] : '';
    const matches = [...brainsSection.matchAll(/id:\s*([a-zA-Z0-9_-]+)/g)];
    nativeRuntimeBrains = matches.map(m => m[1]);
  }

  // 2. Remove stale managed shims safely (only if confirmed managed)
  const existingDestDirs = fs.readdirSync(targetDir, { withFileTypes: true })
    .filter(dirent => dirent.isDirectory())
    .map(dirent => dirent.name);

  for (const existingDir of existingDestDirs) {
    if (nativeRuntimeBrains.includes(existingDir)) {
      // Governed native runtime brain bundle; preserve without pruning
      continue;
    }
    if (!skills.includes(existingDir)) {
      const staleDir = path.join(targetDir, existingDir);
      const staleEntries = fs.readdirSync(staleDir);
      const unexpected = staleEntries.filter(e => e !== 'SKILL.md');
      if (unexpected.length > 0) {
        console.error(`[SAFETY ERROR]: Stale directory ${staleDir} contains unknown files: ${unexpected.join(', ')}. Cannot remove.`);
        process.exit(1);
      }
      const staleSkillMd = path.join(staleDir, 'SKILL.md');
      if (fs.existsSync(staleSkillMd)) {
        const text = fs.readFileSync(staleSkillMd, 'utf8');
        if (!text.includes(MANAGED_MARKER) && !text.includes('This is an agent discovery shim.')) {
          console.error(`[SAFETY ERROR]: Stale directory ${staleDir}/SKILL.md does not contain managed marker. Cannot remove.`);
          process.exit(1);
        }
        fs.unlinkSync(staleSkillMd);
      }
      fs.rmdirSync(staleDir);
      console.log(`  ✓ Safely pruned stale managed shim: ${existingDir}`);
    }
  }

  console.log(`  ✓ Synchronized ${skills.length} thin discovery shims safely in ${relTarget}`);
}

// Security Check: verify zero disallowed binary hooks exist
const disallowedHookPaths = [
  path.join(projectRoot, '.codex', 'hooks.json'),
  path.join(projectRoot, '.agents', 'hooks.json'),
];

for (const hookPath of disallowedHookPaths) {
  if (fs.existsSync(hookPath)) {
    console.error(`[SECURITY VIOLATION]: Unauthorized hook file detected: ${hookPath}`);
    process.exit(1);
  }
}

console.log();
console.log('Security check passed: 0 unauthorized binary hooks.');
console.log('Thin discovery shims synchronized successfully across Codex, Antigravity, and ZCode.');
console.log('====================================================');
